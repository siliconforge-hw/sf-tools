#!/usr/bin/env python3
"""Generate the SF-CS-001 hardware layer header (<ip>_regs_hw.h) from a SystemRDL register map.

Usage: gen_c_hw.py regs/<ip>.rdl > sw/gen/<ip>_regs_hw.h

The root addrmap must be named <ip>_regs. Output, following SF-CS-001:
  - register structure <ip>_regs_t (volatile, volatile const for read-only registers,
    reserved words for address gaps) and <IP>_REGS(base) (SF-030, DP-01)
  - offsets, address span and compile-time layout checks (SF-030, DP-05)
  - field position / mask / reset macros with U suffix (SF-013, SF-015)
  - overridable access hooks <IP>_RD / <IP>_WR (SF-031, DP-02)
  - typed accessors <ip>_regs_<reg>_<field>_<op>, generated only where the RDL software access
    allows them: get (readable), set (writable), clear (W1C). One volatile access per
    expression (SF-033), no read-modify-write on W1C bits (SF-034), parameter validation
    and status return (SF-022, SF-040).

Supported: flat registers of 32 bits in the root addrmap (no arrays, regfiles or nested addrmaps).
"""

import os
import sys

from systemrdl import RDLCompiler, RDLCompileError
from systemrdl.node import AddrmapNode, RegNode, SignalNode
from systemrdl.rdltypes import OnReadType, OnWriteType

W1C = (OnWriteType.woclr, OnWriteType.wclr)


def die(msg):
    print(f"gen_c_hw.py: {msg}", file=sys.stderr)
    sys.exit(1)


def oneline(text):
    return " ".join((text or "").split())


def doc(lines):
    return "\n".join(["/**"] + [f" * {l}".rstrip() for l in lines] + [" */"])


class Gen:
    def __init__(self, top, src):
        self.top = top
        self.src = src
        if not top.inst_name.endswith("_regs"):
            die(f"root addrmap '{top.inst_name}' must be named <ip>_regs")
        self.ip = top.inst_name[: -len("_regs")]
        self.IP = self.ip.upper()
        self.regs = []
        for child in top.children():
            if isinstance(child, SignalNode):
                continue        # signal RDL : matériel seulement (reset paramétré…), rien côté C
            if not isinstance(child, RegNode) or child.is_array:
                die(f"'{child.inst_name}': only flat registers are supported")
            if child.get_property("regwidth") != 32:
                die(f"'{child.inst_name}': only 32-bit registers are supported (SF-032)")
            self.regs.append(child)
        self.regs.sort(key=lambda r: r.address_offset)
        self.out = []
        self.addr_width = 12

    def emit(self, text=""):
        self.out.append(text)

    # ------------------------------------------------------------------
    def header(self):
        name = f"{self.ip}_regs_hw.h"
        self.emit("// ============================================================")
        self.emit(f"// File        : {name}")
        self.emit(f"// Project     : {self.oneline_top('name') or self.IP}")
        self.emit(f"// Description : Hardware layer for {self.ip} : register map structure,")
        self.emit("//               field macros, access hooks and typed accessors")
        self.emit(f"// Reference   : {self.src} (SystemRDL), SF-CS-001")
        self.emit("// Author      : generated by sf-tools/regmap/gen_c_hw.py")
        self.emit("// Version     : generated — DO NOT EDIT, regenerate with `make regs`")
        self.emit("// ============================================================")
        self.emit()
        self.emit(f"#ifndef {self.IP}_REGS_HW_H")
        self.emit(f"#define {self.IP}_REGS_HW_H")
        self.emit()
        self.emit("#include <stddef.h>")
        self.emit("#include <stdint.h>")
        self.emit()
        self.emit("#ifdef __cplusplus")
        self.emit('extern "C" {')
        self.emit("#endif")
        self.emit()

    def oneline_top(self, prop):
        return oneline(self.top.get_property(prop))

    # ------------------------------------------------------------------
    def structure(self):
        self.emit("// ------------------------------------------------------------")
        self.emit("// Register map")
        self.emit("// ------------------------------------------------------------")
        self.emit("// Always access registers as full 32-bit words (SF-032).")
        self.emit("typedef struct {")
        addr, gap = 0, 0
        for r in self.regs:
            if r.address_offset > addr:
                n = (r.address_offset - addr) // 4
                self.emit(f"    volatile const uint32_t RESERVED{gap}[{n}]; // 0x{addr:02X} reserved")
                gap += 1
            ro = not r.has_sw_writable
            qual = "volatile const uint32_t" if ro else "volatile uint32_t"
            self.emit(f"    {qual} {r.inst_name}; // 0x{r.address_offset:02X} {self.access(r):4} "
                      f"{oneline(r.get_property('name'))}")
            addr = r.address_offset + 4
        self.emit(f"}} {self.ip}_regs_t;")
        self.emit()
        self.emit("// MISRA deviation DP-01 : integer (bus address) to pointer conversion")
        self.emit(f"#define {self.IP}_REGS(base) (({self.ip}_regs_t *)(uintptr_t)(base))")
        self.emit()
        self.span = addr

    def access(self, r):
        rd, wr = r.has_sw_readable, r.has_sw_writable
        if any(f.get_property("onwrite") in W1C for f in r.fields()):
            return "RW1C"
        return "RW" if rd and wr else "RO" if rd else "WO"

    def offsets(self):
        self.emit("// ------------------------------------------------------------")
        self.emit("// Register offsets (bytes) and compile-time layout check")
        self.emit("// ------------------------------------------------------------")
        for r in self.regs:
            self.emit(f"#define {self.IP}_{r.inst_name}_OFFSET 0x{r.address_offset:02X}U")
        self.emit()
        self.emit(f"#define {self.IP}_ADDR_SPAN 0x{self.span:02X}U // sizeof({self.ip}_regs_t)")
        self.emit(f"#define {self.IP}_ADDR_WINDOW 0x{1 << self.addr_width:X}U // decoded window (SF-REG-001 REG-1)")
        self.emit()
        self.emit("// MISRA deviation DP-05 : token pasting (C99 has no _Static_assert)")
        self.emit(f"#define {self.IP}_STATIC_ASSERT(cond, name) "
                  f"typedef char {self.ip}_static_assert_##name[(cond) ? 1 : -1]")
        self.emit()
        for r in self.regs:
            self.emit(f"{self.IP}_STATIC_ASSERT(offsetof({self.ip}_regs_t, {r.inst_name}) == "
                      f"{self.IP}_{r.inst_name}_OFFSET, {r.inst_name.lower()});")
        self.emit(f"{self.IP}_STATIC_ASSERT(sizeof({self.ip}_regs_t) == {self.IP}_ADDR_SPAN, span);")
        self.emit()

    def fields(self):
        self.emit("// ------------------------------------------------------------")
        self.emit("// Fields : position, mask, reset value")
        self.emit("// ------------------------------------------------------------")
        for r in self.regs:
            reset, constant = 0, True
            for f in r.fields():
                P = f"{self.IP}_{r.inst_name}_{f.inst_name}"
                mask = ((1 << f.width) - 1) << f.lsb
                self.emit(f"#define {P}_POS   {f.lsb}U")
                self.emit(f"#define {P}_MASK  0x{mask:08X}U")
                rv = f.get_property("reset")
                if isinstance(rv, int):
                    self.emit(f"#define {P}_RESET 0x{rv:X}U")
                    reset |= rv << f.lsb
                else:
                    constant = False
                    src = "hardware-driven, no reset value" if rv is None else \
                        f"reset value from hardware signal {rv.inst_name}"
                    self.emit(f"// {P} : {src}")
            if constant:
                self.emit(f"#define {self.IP}_{r.inst_name}_RESET 0x{reset:08X}U")
            else:
                self.emit(f"// {self.IP}_{r.inst_name}_RESET : not constant (see fields above)")
            self.emit()

    def hooks(self):
        self.emit("// ------------------------------------------------------------")
        self.emit("// Register access hooks (SF-031)")
        self.emit("// ------------------------------------------------------------")
        self.emit("// Every accessor below goes through these two macros. By default they are plain")
        self.emit("// volatile accesses; override them before including this header (Xil_In32/Xil_Out32,")
        self.emit("// tracing, simulation model).")
        self.emit("// MISRA deviation DP-02 : function-like macros operating on an lvalue")
        self.emit(f"#ifndef {self.IP}_RD")
        self.emit(f"#define {self.IP}_RD(reg) (reg)")
        self.emit("#endif")
        self.emit()
        self.emit(f"#ifndef {self.IP}_WR")
        self.emit(f"#define {self.IP}_WR(reg, val) ((reg) = (uint32_t)(val))")
        self.emit("#endif")
        self.emit()

    def status(self):
        self.emit("// ------------------------------------------------------------")
        self.emit("// Status of the accessors that modify the hardware state (SF-022, SF-040)")
        self.emit("// ------------------------------------------------------------")
        self.emit(f"typedef int32_t {self.ip}_regs_status_t;")
        self.emit()
        self.emit(f"#define {self.IP}_REGS_OK        ((({self.ip}_regs_status_t)0))")
        self.emit(f"#define {self.IP}_REGS_ERR_NULL  ((({self.ip}_regs_status_t)-1)) // regs pointer is NULL")
        self.emit(f"#define {self.IP}_REGS_ERR_RANGE ((({self.ip}_regs_status_t)-2)) // value wider than the field")
        self.emit()

    # ------------------------------------------------------------------
    def accessors(self):
        self.non_atomic = []
        self.emit("// ------------------------------------------------------------")
        self.emit("// Typed accessors")
        self.emit("// ------------------------------------------------------------")
        self.emit("// Generated only where the software access of the field allows them.")
        self.emit("// Context : thread or ISR, unless stated otherwise (see Concurrency).")
        self.emit()
        for r in self.regs:
            w1c_mask = sum(((1 << f.width) - 1) << f.lsb for f in r.fields()
                           if f.get_property("onwrite") in W1C)
            for f in r.fields():
                self.field_accessors(r, f, w1c_mask)
        self.emit("// ------------------------------------------------------------")
        self.emit("// Concurrency (SF-062)")
        self.emit("// ------------------------------------------------------------")
        self.emit("// Not atomic (read-modify-write) : protect them when the register is also")
        self.emit("// written from an ISR :")
        for n in self.non_atomic:
            self.emit(f"//   {n}()")
        self.emit()

    def field_accessors(self, r, f, w1c_mask):
        ip, IP = self.ip, self.IP
        R = r.inst_name
        P = f"{IP}_{R}_{f.inst_name}"
        fn = f"{ip}_regs_{R}_{f.inst_name}".lower()
        what = f"{R}.{f.inst_name}"
        desc = oneline(f.get_property("desc"))
        info = [f"Field description : {desc}"] if desc else []
        onwrite = f.get_property("onwrite")
        side_read = f.get_property("swacc") or f.get_property("onread") in (OnReadType.rclr, OnReadType.rset)
        maxval = (1 << f.width) - 1

        if f.is_sw_readable:
            lines = [f"@brief   Read {what} ({f.width} bit(s), [{f.msb}:{f.lsb}])", *info,
                     "@param   [in] regs Register block",
                     "@return  Field value, or 0U without hardware access when regs is NULL"]
            if side_read:
                lines.append("@warning Reading has a hardware side effect (swacc/rclr) : "
                             "do not read for mere observation.")
            self.emit(doc(lines))
            self.emit(f"static inline uint32_t {fn}_get(const {ip}_regs_t *regs)")
            self.emit("{")
            self.emit("    uint32_t value = 0U;")
            self.emit("    if (regs != NULL) {")
            self.emit(f"        value = ({IP}_RD(regs->{R}) & {P}_MASK) >> {P}_POS;")
            self.emit("    }")
            self.emit("    return value;")
            self.emit("}")
            self.emit()

        if onwrite in W1C:
            self.emit(doc([f"@brief   Clear {what} (write 1 to clear)", *info,
                           "@param   [in] regs Register block",
                           f"@return  {IP}_REGS_OK, or {IP}_REGS_ERR_NULL",
                           "@note    Writes only this field's mask : the other W1C bits are untouched "
                           "(SF-034). Atomic."]))
            self.emit(f"static inline {ip}_regs_status_t {fn}_clear({ip}_regs_t *regs)")
            self.emit("{")
            self.emit(f"    {ip}_regs_status_t status = {IP}_REGS_ERR_NULL;")
            self.emit("    if (regs != NULL) {")
            self.emit(f"        {IP}_WR(regs->{R}, {P}_MASK);")
            self.emit(f"        status = {IP}_REGS_OK;")
            self.emit("    }")
            self.emit("    return status;")
            self.emit("}")
            self.emit()
        elif f.is_sw_writable:
            rmw = f.is_sw_readable and len(list(r.fields())) > 1
            note = []
            if f.get_property("swmod"):
                note.append("@note    Writing triggers a hardware action (swmod pulse).")
            if rmw:
                note.append("@note    Read-modify-write : not atomic (see Concurrency)."
                            + (" W1C bits of the register are written as 0." if w1c_mask else ""))
                self.non_atomic.append(f"{fn}_set")
            elif not f.is_sw_readable:
                note.append("@note    Write-only register : direct write, the other fields receive 0.")
            self.emit(doc([f"@brief   Write {what} ({f.width} bit(s), [{f.msb}:{f.lsb}])", *info,
                           "@param   [in] regs  Register block",
                           f"@param   [in] value New value, 0 to {maxval}U",
                           f"@return  {IP}_REGS_OK, {IP}_REGS_ERR_NULL, or {IP}_REGS_ERR_RANGE "
                           "(nothing written)", *note]))
            self.emit(f"static inline {ip}_regs_status_t {fn}_set({ip}_regs_t *regs, uint32_t value)")
            self.emit("{")
            self.emit(f"    {ip}_regs_status_t status = {IP}_REGS_OK;")
            self.emit("    if (regs == NULL) {")
            self.emit(f"        status = {IP}_REGS_ERR_NULL;")
            self.emit(f"    }} else if (value > {maxval}U) {{")
            self.emit(f"        status = {IP}_REGS_ERR_RANGE;")
            self.emit("    } else {")
            if rmw:
                self.emit(f"        uint32_t reg = {IP}_RD(regs->{R});")
                keep = f"~{P}_MASK" + (f" & ~0x{w1c_mask:08X}U" if w1c_mask else "")
                self.emit(f"        reg = (reg & {keep}) | ((value << {P}_POS) & {P}_MASK);")
                self.emit(f"        {IP}_WR(regs->{R}, reg);")
            else:
                self.emit(f"        {IP}_WR(regs->{R}, (value << {P}_POS) & {P}_MASK);")
            self.emit("    }")
            self.emit("    return status;")
            self.emit("}")
            self.emit()

    def footer(self):
        self.emit("#ifdef __cplusplus")
        self.emit("}")
        self.emit("#endif")
        self.emit()
        self.emit(f"#endif /* {self.IP}_REGS_HW_H */")

    def run(self):
        self.header()
        self.structure()
        self.offsets()
        self.fields()
        self.hooks()
        self.status()
        self.accessors()
        self.footer()
        return "\n".join(self.out) + "\n"


def check_ip_num(top, ip_id):
    """SF-REG-001 REG-5 : ID.IP_NUM de la carte == numéro de IP_ID (sf-project.env)."""
    reg = next((r for r in top.registers() if r.inst_name == "ID"), None)
    if reg is None or not ip_id:
        return
    field = next((f for f in reg.fields() if f.inst_name == "IP_NUM"), None)
    if field is None:
        return
    expected = int(ip_id[2:]) if ip_id.startswith("IP") and ip_id[2:].isdigit() else None
    if expected is not None and field.get_property("reset") != expected:
        die(f"ID.IP_NUM = {field.get_property('reset')} mais sf-project.env déclare IP_ID={ip_id} "
            f"(SF-REG-001 REG-5)")


def main():
    args, incdirs, addr_width = [], [], 12
    it = iter(sys.argv[1:])
    for a in it:
        if a == "-I":
            incdirs.append(next(it, ""))
        elif a == "--addr-width":
            addr_width = int(next(it, "12"))
        else:
            args.append(a)
    if len(args) != 1:
        die("usage: gen_c_hw.py [-I dir]... regs/<ip>.rdl")
    rdlc = RDLCompiler()
    try:
        rdlc.compile_file(args[0], incl_search_paths=incdirs)
        top = rdlc.elaborate().top
    except RDLCompileError:
        sys.exit(1)
    if not isinstance(top, AddrmapNode):
        die("root component must be an addrmap")
    check_ip_num(top, os.environ.get("SF_IP_ID", ""))
    gen = Gen(top, args[0])
    gen.addr_width = addr_width
    if gen.regs and gen.regs[-1].address_offset + 4 > (1 << addr_width):
        die(f"la carte dépasse la fenêtre de {1 << addr_width} octets (--addr-width {addr_width})")
    sys.stdout.write(gen.run())


if __name__ == "__main__":
    main()
